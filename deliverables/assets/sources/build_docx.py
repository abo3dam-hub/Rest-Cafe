BRAND = RGBColor(0x7C, 0x2D, 0x12)
BRAND2 = RGBColor(0x9A, 0x34, 0x12)
GREY = RGBColor(0x6B, 0x72, 0x80)

def _rtl(p):
    pPr = p._p.get_or_add_pPr()
    bidi = OxmlElement('w:bidi'); bidi.set(qn('w:val'), '1'); pPr.append(bidi)
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    return p

def _font(run, name='Noto Sans Arabic', size=11, bold=False, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None: run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts'); rPr.append(rFonts)
    for tag in ('w:ascii', 'w:hAnsi', 'w:cs'):
        rFonts.set(qn(tag), name)
    return run

def body(doc, text, size=11, bold=False, align_right=True, space_after=6, color=None):
    p = doc.add_paragraph()
    _rtl(p)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.5
    _font(p.add_run(text), size=size, bold=bold, color=color)
    return p

def h1(doc, text):
    p = doc.add_paragraph()
    _rtl(p)
    p.paragraph_format.space_before = Pt(14); p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.page_break_before = True
    _font(p.add_run(text), name='Noto Kufi Arabic', size=17, bold=True, color=BRAND)
    return p

def h2(doc, text):
    p = doc.add_paragraph()
    _rtl(p)
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(5)
    _font(p.add_run(text), name='Noto Kufi Arabic', size=13.5, bold=True, color=BRAND2)
    return p

def h3(doc, text):
    p = doc.add_paragraph()
    _rtl(p)
    p.paragraph_format.space_before = Pt(9); p.paragraph_format.space_after = Pt(4)
    _font(p.add_run(text), name='Noto Kufi Arabic', size=11.5, bold=True)
    return p

def bullets(doc, items, numbered=False):
    for i, it in enumerate(items, 1):
        p = doc.add_paragraph()
        _rtl(p)
        p.paragraph_format.space_after = Pt(3)
        p.paragraph_format.line_spacing = 1.45
        prefix = f'{i}. ' if numbered else '• '
        _font(p.add_run(prefix + it), size=11)

def steps(doc, items):
    bullets(doc, items, numbered=True)

def note(doc, kind, text):
    labels = {'note': 'ملاحظة: ', 'tip': 'نصيحة: ', 'warn': 'تنبيه: '}
    p = doc.add_paragraph()
    _rtl(p)
    p.paragraph_format.space_before = Pt(6); p.paragraph_format.space_after = Pt(8)
    _font(p.add_run(labels[kind]), size=10.5, bold=True, color=BRAND2)
    _font(p.add_run(text), size=10.5)
    return p

def img(doc, path, caption=None, width_mm=150):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(path, width=Mm(width_mm))
    if caption:
        c = doc.add_paragraph(); c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        _font(c.add_run(caption), size=9, color=GREY)
    return p

def table(doc, headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htxt in enumerate(headers):
        hdr[i].text = ''
        p = hdr[i].paragraphs[0]; _rtl(p)
        _font(p.add_run(htxt), size=10.5, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]; _rtl(p)
            _font(p.add_run(val), size=10.5)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

def new_doc(page_w=210, page_h=297, margin=17):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width = Mm(page_w); sec.page_height = Mm(page_h)
    sec.left_margin = sec.right_margin = Mm(margin)
    sec.top_margin = Mm(15); sec.bottom_margin = Mm(15)
    # RTL section
    secPr = sec._sectPr
    bidi = OxmlElement('w:bidi'); bidi.set(qn('w:val'), '1'); secPr.append(bidi)
    style = doc.styles['Normal']
    style.font.name = 'Noto Sans Arabic'
    style.font.size = Pt(11)
    return doc

def title_block(doc, title, subtitle, meta_lines):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _font(p.add_run('Rest&Cafe'), name='Noto Kufi Arabic', size=26, bold=True, color=BRAND)
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _font(p.add_run(title), name='Noto Kufi Arabic', size=20, bold=True, color=BRAND2)
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _font(p.add_run(subtitle), size=13, color=GREY)
    for m in meta_lines:
        p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        _font(p.add_run(m), size=10.5, color=GREY)


